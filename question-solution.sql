-- Show all campaigns and their total revenue.
-- Even if a campaign has no ads or no performance yet.

 SELECT 
    c.campaign_name,
    COALESCE(SUM(dp.revenue), 0) AS total_revenue
FROM campaigns c
LEFT JOIN ads a
    ON c.campaign_id = a.campaign_id
LEFT JOIN daily_performance dp
    ON a.ad_id = dp.ad_id
GROUP BY c.campaign_name;
