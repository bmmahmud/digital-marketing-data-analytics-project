-- Show total revenue generated by each ad along with its campaign name.
SELECT 
    c.campaign_name,
    a.ad_name,
    SUM(dp.revenue) AS total_revenue
FROM daily_performance dp
JOIN ads a 
    ON a.ad_id = dp.ad_id
JOIN campaigns c
    ON c.campaign_id = a.campaign_id
GROUP BY c.campaign_name, a.ad_name
ORDER BY total_revenue DESC;

