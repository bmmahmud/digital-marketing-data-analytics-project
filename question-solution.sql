-- What is the total impressions, total clicks, total conversions and total revenue for each campaign?
-- Show total revenue per channel
select cam.channel, 
sum(dp.revenue) as Revenue, 
sum(impressions) as Impressions,
sum(clicks) as clicks,
sum(conversions) as conversion 
from daily_performance as dp
join ads 
on ads.ad_id = dp.ad_id
join campaigns cam
on cam.campaign_id = ads.campaign_id
group by cam.channel;

-- -----------------------
-- Which campaign has the highest ROAS?
-- Reminder: ROAS = Revenue / Spend

-- Write a query that:
-- Shows campaign_name
-- Total revenue
-- Total spend
-- ROAS
-- Orders by ROAS descending
-- Answer
SELECT 
    c.campaign_name,
    SUM(dp.revenue) AS total_revenue,
    SUM(dp.spend) AS total_spend,
    ROUND(
        SUM(dp.revenue) / NULLIF(SUM(dp.spend), 0), 2
    ) AS ROAS
FROM daily_performance dp
JOIN ads a 
    ON a.ad_id = dp.ad_id
JOIN campaigns c 
    ON c.campaign_id = a.campaign_id
GROUP BY c.campaign_name
ORDER BY ROAS DESC;
